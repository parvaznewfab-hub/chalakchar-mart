#!/usr/bin/env node
// Copies the policy page texts the app shows (lib/pages/user/policy_texts.dart,
// the texts used while health features are off) into
// functions/seo/policyTexts.js, so the server HTML for /about-us,
// /privacy-policy, /terms-conditions and /return-policy carries the same
// words. functions/test/seoPolicyTexts.test.js fails when the two differ.
//
// Usage: node tools/seo/sync_policy_texts.js        (writes the JS file)
//        node tools/seo/sync_policy_texts.js --check (exit 1 when out of date)

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..", "..");
const DART_FILE = path.join(ROOT, "lib", "pages", "user", "policy_texts.dart");
const JS_FILE = path.join(ROOT, "functions", "seo", "policyTexts.js");

const CONSTANTS = {
  kAboutUsNoHealth: "/about-us",
  kPrivacyPolicyNoHealth: "/privacy-policy",
  kTermsNoHealth: "/terms-conditions",
  kReturnPolicyNoHealth: "/return-policy",
};

/** The `const String name = '''...''';` texts of [dartSource], by name. */
function parseDartTexts(dartSource) {
  const out = {};
  const re = /const String (\w+) = '''([\s\S]*?)''';/g;
  let m;
  while ((m = re.exec(dartSource))) {
    // The file uses no escapes or interpolation; refuse if that changes,
    // rather than copying a "\n" or "$x" literally.
    if (/[\\$]/.test(m[2])) throw new Error(`${m[1]}: escapes/interpolation are not supported`);
    out[m[1]] = m[2].replace(/\r\n/g, "\n");
  }
  return out;
}

function buildJs(dartSource) {
  const texts = parseDartTexts(dartSource);
  const pages = {};
  for (const [name, route] of Object.entries(CONSTANTS)) {
    if (typeof texts[name] !== "string") throw new Error(`${name} not found in policy_texts.dart`);
    pages[route] = texts[name];
  }
  return `// GENERATED by tools/seo/sync_policy_texts.js from
// lib/pages/user/policy_texts.dart — do not edit by hand; change the Dart
// file and run the script again.
//
// Same text the app shows (health features off). The contact phone/email in
// the text are replaced with settings/app's values when the page is served,
// as the app does (lib/utils/contact_info.dart withSettingsContacts).

module.exports = ${JSON.stringify(pages, null, 2)};
`;
}

if (require.main === module) {
  const expected = buildJs(fs.readFileSync(DART_FILE, "utf8"));
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(JS_FILE) ? fs.readFileSync(JS_FILE, "utf8") : "";
    if (current !== expected) {
      console.error("functions/seo/policyTexts.js is out of date: run node tools/seo/sync_policy_texts.js");
      process.exit(1);
    }
    console.log("policyTexts.js is up to date");
  } else {
    fs.writeFileSync(JS_FILE, expected);
    console.log(`wrote ${path.relative(ROOT, JS_FILE)}`);
  }
}

module.exports = { parseDartTexts, buildJs, DART_FILE, JS_FILE };
